"""Generate a minimal, pinned capability snapshot from Tasshack/dreame-vacuum.

Only model names and firmware thresholds are exported, never device keys/resources.
Usage: python3 scripts/import-ha-capabilities.py /path/to/dreame-vacuum
"""
import ast
import base64
import json
from pathlib import Path
import subprocess
import sys
import zlib

REVISION = "bba1d35429393b085583fb82cef1ff441e1de98b"
FLAGS = ["CLEANGENIUS", "MOP_PAD_LIFTING", "MOP_PAD_LIFTING_PLUS",
         "MOP_PAD_UNMOUNTING", "NEW_STATE", "GEN5", "EMBEDDED_TANK"]

source = Path(sys.argv[1]).resolve()
revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
if revision != REVISION:
    raise SystemExit("Review a new upstream revision before changing the pinned importer")
def upstream_file(name):
    return subprocess.check_output(["git", "-C", str(source), "show",
                                    f"{REVISION}:custom_components/dreame_vacuum/dreame/{name}"], text=True)


tree = ast.parse(upstream_file("const.py"))
encoded = next(ast.literal_eval(node.value) for node in tree.body
               if isinstance(node, (ast.Assign, ast.AnnAssign))
               and any(isinstance(target, ast.Name) and target.id == "DEVICE_INFO"
                       for target in (node.targets if isinstance(node, ast.Assign) else [node.target])))
data = json.loads(zlib.decompress(base64.b64decode(encoded), zlib.MAX_WBITS | 32))
types = ast.parse(upstream_file("types.py"))
enum = next(node for node in types.body if isinstance(node, ast.ClassDef) and node.name == "DeviceCapability")
labels = {ast.literal_eval(node.value): node.targets[0].id for node in enum.body
          if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant)}
profiles = []
models = {}
for model, index in sorted(data[3].items()):
    entry = data[0][index]
    if len(entry) not in (3, 4) or entry[2] < 0:
        continue
    capabilities = {labels.get(cap[0]): cap[1] for cap in data[1][entry[2]] or []}
    profile = [capabilities.get(flag) for flag in FLAGS]
    if any(value is not None and not isinstance(value, int) for value in profile):
        raise SystemExit(f"Unexpected non-threshold value for {model}")
    if profile not in profiles:
        profiles.append(profile)
    models[model] = profiles.index(profile)
snapshot = {"revision": revision, "flags": FLAGS, "profiles": profiles, "models": models}
destination = Path(__file__).resolve().parents[1] / "src/dreame/ha-capabilities.generated.ts"
destination.write_text(
    "// Generated by scripts/import-ha-capabilities.py. Do not edit manually.\n"
    "// Derived from Tasshack/dreame-vacuum; Copyright (c) 2022 Tasshack, MIT.\n"
    "// See third-party/dreame-vacuum-LICENSE.txt and docs/capabilities.md.\n"
    "export const HA_CAPABILITIES: { revision: string; flags: string[]; "
    "profiles: Array<Array<number | null>>; models: Record<string, number> } = "
    + json.dumps(snapshot, indent=2, ensure_ascii=True) + ";\n"
)
print(f"Imported {len(models)} models and {len(profiles)} capability profiles at {revision}")
